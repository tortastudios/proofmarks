// Writes the Homebrew formula for a release from the standalone archives' checksums, for the tortastudios/homebrew-tap
// repository (Formula/proofmarks.rb). Run after build-standalone.mjs has built the macOS and Linux targets.
//
//   node scripts/homebrew-formula.mjs [--base <download url>] [--from <folder>] [--out <file>]
//
// --base defaults to the GitHub release for package.json's version; --from is where the .sha256 files are (default .standalone).
import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';

const args = process.argv.slice(2);
const option = name => {
  const index = args.indexOf(name);
  return index < 0 ? undefined : args[index + 1];
};
const root = path.resolve(import.meta.dirname, '..');
const { version } = JSON.parse(await readFile(path.join(root, 'package.json'), 'utf8'));
const base = (option('--base') ?? `https://github.com/tortastudios/proofmarks/releases/download/v${version}`).replace(
  /\/$/,
  '',
);
const out = path.resolve(option('--out') ?? path.join(root, '.standalone/homebrew/proofmarks.rb'));
const from = path.resolve(option('--from') ?? path.join(root, '.standalone'));

async function download(target) {
  const file = `proofmarks-${version}-${target}.tar.gz`;
  const sha256 = (await readFile(path.join(from, `${file}.sha256`), 'utf8')).split(/\s+/)[0];
  if (!/^[0-9a-f]{64}$/.test(sha256 ?? '')) throw new Error(`No SHA-256 for ${file}; build that target first`);
  return `      url "${base}/${file}"\n      sha256 "${sha256}"`;
}

const formula = `# Generated by scripts/homebrew-formula.mjs in tortastudios/proofmarks; edit the script, not this file.
class Proofmarks < Formula
  desc "Marks what reads like AI slop on your page and says why"
  homepage "https://github.com/tortastudios/proofmarks"
  version "${version}"
  license "FSL-1.1-MIT"

  on_macos do
    on_arm do
${await download('darwin-arm64')}
    end
    on_intel do
${await download('darwin-x64')}
    end
  end

  on_linux do
    on_arm do
${await download('linux-arm64')}
    end
    on_intel do
${await download('linux-x64')}
    end
  end

  def install
    # The program reads its rules and page scripts from beside it, so the whole archive stays together.
    libexec.install Dir["*"]
    bin.install_symlink libexec/"dist/companion/proofmarks"
  end

  test do
    assert_match "Usage: proofmarks", shell_output("#{bin}/proofmarks --help")
  end
end
`;
await mkdir(path.dirname(out), { recursive: true });
await writeFile(out, formula);
console.log(path.relative(root, out));
